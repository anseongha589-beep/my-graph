#
# 이 프로그램은 KOBIS 일별 박스오피스 데이터를 가져와
# 영화별 일관객 변화를 그래프로 보여주는 Streamlit 앱입니다.
#
# 데이터 주소:
# https://raw.githubusercontent.com/greatsong/modudata/main/data/kobis_daily.csv
#
# ============================================


# --------------------------------------------
# 1. 필요한 라이브러리 불러오기
# --------------------------------------------

import streamlit as st
import pandas as pd
import altair as alt


# --------------------------------------------
# 2. Streamlit 화면 기본 설정
# --------------------------------------------

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide"
)


# --------------------------------------------
# 3. 앱 제목
# --------------------------------------------

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.write(
    "영화를 선택하면 1년 동안의 일관객 변화를 "
    "시간에 따라 확인할 수 있습니다."
)


# --------------------------------------------
# 4. 데이터 주소
# --------------------------------------------

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/modudata/"
    "main/data/kobis_daily.csv"
)


# --------------------------------------------
# 5. 데이터 불러오기
# --------------------------------------------
# 인터넷에서 CSV 파일을 가져옵니다.
#
# @st.cache_data를 사용하면 앱을 다시 실행할 때마다
# 인터넷에서 데이터를 반복해서 다운로드하지 않습니다.

@st.cache_data
def load_data():
    """CSV 데이터를 불러와 정리하는 함수"""

    df = pd.read_csv(DATA_URL)

    return df


# --------------------------------------------
# 6. 데이터 불러오기
# --------------------------------------------

try:
    df = load_data()

except Exception as e:
    st.error("데이터를 불러오지 못했습니다.")

    st.info(
        """
        **확인할 사항**

        1. 인터넷 연결이 정상인지 확인하세요.
        2. 데이터 주소가 정상적으로 열리는지 확인하세요.
        3. GitHub의 데이터 파일이 삭제되거나 이동되지 않았는지 확인하세요.
        """
    )

    st.stop()


# --------------------------------------------
# 7. 데이터가 비어 있는지 확인
# --------------------------------------------

if df.empty:
    st.error("데이터가 비어 있습니다.")

    st.info(
        "CSV 파일에 영화 데이터가 들어 있는지 확인해 주세요."
    )

    st.stop()


# --------------------------------------------
# 8. 날짜 열을 진짜 날짜로 변환
# --------------------------------------------
# CSV의 날짜는
#
# 20250101
# 20250102
# 20250103
#
# 같은 형태로 되어 있습니다.
#
# 이것을 pandas의 날짜(datetime) 형식으로 변환합니다.

df["날짜"] = pd.to_datetime(
    df["날짜"].astype(str),
    format="%Y%m%d",
    errors="coerce"
)


# --------------------------------------------
# 9. 숫자 열을 숫자로 변환
# --------------------------------------------
# 혹시 숫자가 문자열로 저장되어 있더라도
# 그래프와 계산에 사용할 수 있도록 숫자로 변환합니다.

numeric_columns = [
    "순위",
    "일관객",
    "누적관객",
    "스크린수",
    "상영횟수"
]

for column in numeric_columns:
    if column in df.columns:
        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )


# --------------------------------------------
# 10. 영화명 정리
# --------------------------------------------
# 영화명이 비어 있는 행은 그래프에서 사용할 수 없으므로
# 제거합니다.

df = df.dropna(
    subset=["날짜", "영화명", "일관객"]
).copy()


# --------------------------------------------
# 11. 날짜순으로 데이터 정렬
# --------------------------------------------

df = df.sort_values(
    by=["날짜", "순위"],
    ascending=[True, True]
).reset_index(drop=True)


# --------------------------------------------
# 12. 데이터 기본 정보
# --------------------------------------------

min_date = df["날짜"].min()
max_date = df["날짜"].max()

movie_count = df["영화명"].nunique()


# --------------------------------------------
# 13. 앱 상단 데이터 정보
# --------------------------------------------

info1, info2, info3 = st.columns(3)

with info1:
    st.metric(
        "데이터 시작일",
        min_date.strftime("%Y-%m-%d")
    )

with info2:
    st.metric(
        "데이터 마지막 날짜",
        max_date.strftime("%Y-%m-%d")
    )

with info3:
    st.metric(
        "영화 종류",
        f"{movie_count:,}편"
    )


st.divider()


# ============================================================
# 그래프 구역 1
# ============================================================

st.header("📈 그래프 1. 영화별 일관객 변화")

st.write(
    "영화를 하나 선택하면 해당 영화가 기록된 날짜별 "
    "일관객 변화를 선 그래프로 확인할 수 있습니다."
)


# --------------------------------------------
# 14. 영화 선택 드롭다운
# --------------------------------------------

movie_list = sorted(
    df["영화명"].dropna().unique().tolist()
)


selected_movie = st.selectbox(
    "🎬 영화를 선택하세요",
    movie_list
)


# --------------------------------------------
# 15. 선택한 영화의 데이터만 가져오기
# --------------------------------------------

movie_df = df[
    df["영화명"] == selected_movie
].copy()


# 날짜순으로 정렬
movie_df = movie_df.sort_values(
    "날짜"
).reset_index(drop=True)


# --------------------------------------------
# 16. 그래프용 데이터 만들기
# --------------------------------------------
# Altair에서 사용하기 편하도록
# 날짜와 관객수 열을 명확하게 준비합니다.

chart_df = movie_df[
    ["날짜", "일관객"]
].copy()


# --------------------------------------------
# 17. 마우스 올리기용 툴팁
# --------------------------------------------
# 그래프 위의 점에 마우스를 올리면
# 날짜와 관객수가 표시되도록 합니다.
#
# Altair의 tooltip 기능을 사용합니다.

tooltip = [
    alt.Tooltip(
        "날짜:T",
        title="날짜",
        format="%Y-%m-%d"
    ),
    alt.Tooltip(
        "일관객:Q",
        title="관객수",
        format=","
    )
]


# --------------------------------------------
# 18. 선 그래프 만들기
# --------------------------------------------
# 선 + 점을 함께 표시합니다.
#
# 점 위에 마우스를 올리면 툴팁이 나타납니다.

line_chart = (
    alt.Chart(chart_df)
    .mark_line(
        point=alt.OverlayMarkDef(
            filled=True,
            size=45
        )
    )
    .encode(
        x=alt.X(
            "날짜:T",
            title="날짜",
            axis=alt.Axis(
                format="%m-%d",
                labelAngle=-45
            )
        ),
        y=alt.Y(
            "일관객:Q",
            title="일관객수",
            axis=alt.Axis(
                format=","
            )
        ),
        tooltip=tooltip
    )
    .properties(
        height=450
    )
    .interactive()
)


# --------------------------------------------
# 19. 그래프 화면에 표시
# --------------------------------------------

st.altair_chart(
    line_chart,
    use_container_width=True
)


# --------------------------------------------
# 20. 그래프 설명 자리
# --------------------------------------------

st.markdown("### 💡 이 그래프로 알 수 있는 것")

st.info(
    f"「{selected_movie}」의 날짜별 일관객이 "
    "시간에 따라 어떻게 증가하거나 감소했는지 확인할 수 있습니다."
)


# --------------------------------------------
# 그래프 1 끝
# --------------------------------------------


st.divider()


# ============================================================
# 그래프 구역 2
