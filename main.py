st.header("📊 그래프 3")

st.info(
    "앞으로 새로운 그래프를 추가할 수 있는 공간입니다."
)

st.markdown("### 💡 이 그래프로 알 수 있는 것")

st.write(
    "여기에 그래프를 추가한 뒤, "
    "그래프를 통해 알 수 있는 내용을 한 문장으로 작성합니다."
)


st.divider()


